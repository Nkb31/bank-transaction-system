const express = require("express");
const authController = require("../controller/auth.controller");
const router = express.Router();
router.post("/register", authController.userRegisterController);
router.post("/login", authController.userLoginCOntroller);
router.post("/login/verify-otp", authController.verifyLoginOtpController);
router.post("/password-reset/request", authController.requestPasswordResetController);
router.post("/password-reset/confirm", authController.resetPasswordController);
router.get("/verify-email", authController.verifyEmailController);
router.post("/resend-verification", authController.resendVerificationEmailController);
router.post("/logout", authController.userLogoutController);
module.exports = router;
